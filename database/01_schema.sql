-- Safely drop existing tables if they exist
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'REPORTS', 'NOTIFICATIONS', 'CERTIFICATES', 'RATINGS', 
        'SESSION_ATTENDANCE', 'CREDIT_TRANSACTIONS', 'SESSIONS', 
        'CREDIT_ACCOUNTS', 'MATCHES', 'AVAILABILITY', 'SKILL_REQUESTS', 
        'USER_SKILLS', 'SKILLS', 'SKILL_CATEGORIES', 'USERS'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. USERS TABLE
-- Stores student and administrator accounts.
-- ----------------------------------------------------------------------------
CREATE TABLE Users (
    user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100) NOT NULL,
    email           VARCHAR2(120) NOT NULL CONSTRAINT uk_users_email UNIQUE,
    password        VARCHAR2(255) NOT NULL,
    department      VARCHAR2(50) DEFAULT 'CSE' NOT NULL,
    year            NUMBER(1) DEFAULT 2 NOT NULL CONSTRAINT chk_users_year CHECK (year BETWEEN 1 AND 5),
    phone           VARCHAR2(20),
    role            VARCHAR2(20) DEFAULT 'STUDENT' NOT NULL CONSTRAINT chk_users_role CHECK (role IN ('STUDENT', 'ADMIN')),
    status          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED')),
    join_date       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chk_users_email_domain CHECK (email LIKE '%@vitstudent.ac.in' OR email LIKE '%@vit.ac.in')
);

-- ----------------------------------------------------------------------------
-- 2. SKILL_CATEGORIES TABLE
-- High-level skill domains (e.g. Programming, Creative, Academics).
-- ----------------------------------------------------------------------------
CREATE TABLE Skill_Categories (
    category_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name   VARCHAR2(100) NOT NULL CONSTRAINT uk_category_name UNIQUE,
    description     VARCHAR2(500)
);

-- ----------------------------------------------------------------------------
-- 3. SKILLS TABLE
-- Specific skills categorized under categories.
-- ----------------------------------------------------------------------------
CREATE TABLE Skills (
    skill_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name      VARCHAR2(100) NOT NULL CONSTRAINT uk_skill_name UNIQUE,
    category_id     NUMBER NOT NULL CONSTRAINT fk_skills_category REFERENCES Skill_Categories(category_id) ON DELETE CASCADE,
    description     VARCHAR2(500)
);

-- ----------------------------------------------------------------------------
-- 4. USER_SKILLS TABLE (Skills Offered to Teach)
-- Junction table resolving N:M relationship between Users and Skills for teaching.
-- ----------------------------------------------------------------------------
CREATE TABLE User_Skills (
    user_skill_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             NUMBER NOT NULL CONSTRAINT fk_userskills_user REFERENCES Users(user_id) ON DELETE CASCADE,
    skill_id            NUMBER NOT NULL CONSTRAINT fk_userskills_skill REFERENCES Skills(skill_id) ON DELETE CASCADE,
    proficiency_level   VARCHAR2(20) DEFAULT 'INTERMEDIATE' NOT NULL 
                        CONSTRAINT chk_prof_level CHECK (proficiency_level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT')),
    experience_years    NUMBER(4,1) DEFAULT 1.0 NOT NULL CONSTRAINT chk_exp_years CHECK (experience_years >= 0),
    available_hours     NUMBER(4,1) DEFAULT 5.0 NOT NULL CONSTRAINT chk_avail_hours CHECK (available_hours >= 0),
    status              VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL 
                        CONSTRAINT chk_userskill_status CHECK (status IN ('AVAILABLE', 'BUSY', 'INACTIVE')),
    CONSTRAINT uk_user_offered_skill UNIQUE (user_id, skill_id)
);

-- ----------------------------------------------------------------------------
-- 5. SKILL_REQUESTS TABLE (Skills Wanted to Learn)
-- Represents skills requested by learners.
-- ----------------------------------------------------------------------------
CREATE TABLE Skill_Requests (
    request_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         NUMBER NOT NULL CONSTRAINT fk_requests_user REFERENCES Users(user_id) ON DELETE CASCADE,
    skill_id        NUMBER NOT NULL CONSTRAINT fk_requests_skill REFERENCES Skills(skill_id) ON DELETE CASCADE,
    desired_level   VARCHAR2(20) DEFAULT 'BEGINNER' NOT NULL 
                    CONSTRAINT chk_req_level CHECK (desired_level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED', 'EXPERT')),
    priority        VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL 
                    CONSTRAINT chk_req_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH')),
    request_date    DATE DEFAULT SYSDATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'PENDING' NOT NULL 
                    CONSTRAINT chk_req_status CHECK (status IN ('PENDING', 'MATCHED', 'FULFILLED', 'CANCELLED'))
);

-- ----------------------------------------------------------------------------
-- 6. AVAILABILITY TABLE
-- Mentors' weekly time schedules for sessions.
-- ----------------------------------------------------------------------------
CREATE TABLE Availability (
    availability_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         NUMBER NOT NULL CONSTRAINT fk_avail_user REFERENCES Users(user_id) ON DELETE CASCADE,
    day_of_week     VARCHAR2(20) NOT NULL 
                    CONSTRAINT chk_avail_day CHECK (day_of_week IN ('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday')),
    start_time      VARCHAR2(10) NOT NULL,
    end_time        VARCHAR2(10) NOT NULL,
    status          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL 
                    CONSTRAINT chk_avail_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

-- ----------------------------------------------------------------------------
-- 7. MATCHES TABLE
-- Algorithmically scored matches between a skill request and a prospective mentor.
-- ----------------------------------------------------------------------------
CREATE TABLE Matches (
    match_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id      NUMBER NOT NULL CONSTRAINT fk_matches_req REFERENCES Skill_Requests(request_id) ON DELETE CASCADE,
    mentor_id       NUMBER NOT NULL CONSTRAINT fk_matches_mentor REFERENCES Users(user_id) ON DELETE CASCADE,
    match_score     NUMBER(5,2) DEFAULT 0 NOT NULL CONSTRAINT chk_match_score CHECK (match_score BETWEEN 0 AND 100),
    match_date      DATE DEFAULT SYSDATE NOT NULL,
    status          VARCHAR2(20) DEFAULT 'PROPOSED' NOT NULL 
                    CONSTRAINT chk_match_status CHECK (status IN ('PROPOSED', 'ACCEPTED', 'DECLINED', 'SCHEDULED'))
);

-- ----------------------------------------------------------------------------
-- 8. CREDIT_ACCOUNTS TABLE (1:1 with Users)
-- Tracks skill credits, lifetime earnings, and lifetime spendings.
-- ----------------------------------------------------------------------------
CREATE TABLE Credit_Accounts (
    account_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         NUMBER NOT NULL CONSTRAINT uk_credit_user UNIQUE 
                    CONSTRAINT fk_credit_user REFERENCES Users(user_id) ON DELETE CASCADE,
    balance         NUMBER(10,2) DEFAULT 50.00 NOT NULL CONSTRAINT chk_credit_bal CHECK (balance >= 0),
    total_earned    NUMBER(10,2) DEFAULT 0.00 NOT NULL CONSTRAINT chk_credit_earned CHECK (total_earned >= 0),
    total_spent     NUMBER(10,2) DEFAULT 0.00 NOT NULL CONSTRAINT chk_credit_spent CHECK (total_spent >= 0),
    last_updated    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 9. SESSIONS TABLE
-- Scheduled peer-to-peer learning sessions between a mentor and learner.
-- ----------------------------------------------------------------------------
CREATE TABLE Sessions (
    session_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id        NUMBER CONSTRAINT fk_sessions_match REFERENCES Matches(match_id) ON DELETE SET NULL,
    mentor_id       NUMBER NOT NULL CONSTRAINT fk_sessions_mentor REFERENCES Users(user_id) ON DELETE CASCADE,
    learner_id      NUMBER NOT NULL CONSTRAINT fk_sessions_learner REFERENCES Users(user_id) ON DELETE CASCADE,
    skill_id        NUMBER NOT NULL CONSTRAINT fk_sessions_skill REFERENCES Skills(skill_id) ON DELETE CASCADE,
    scheduled_date  DATE NOT NULL,
    start_time      VARCHAR2(10) NOT NULL,
    end_time        VARCHAR2(10) NOT NULL,
    duration        NUMBER(4,1) DEFAULT 1.0 NOT NULL CONSTRAINT chk_session_duration CHECK (duration > 0),
    credit_cost     NUMBER(10,2) DEFAULT 10.00 NOT NULL CONSTRAINT chk_session_cost CHECK (credit_cost >= 0),
    status          VARCHAR2(20) DEFAULT 'REQUESTED' NOT NULL 
                    CONSTRAINT chk_session_status CHECK (status IN ('REQUESTED', 'ACCEPTED', 'SCHEDULED', 'COMPLETED', 'CANCELLED', 'REJECTED')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    completed_at    TIMESTAMP,
    CONSTRAINT chk_session_distinct_users CHECK (mentor_id <> learner_id)
);

-- ----------------------------------------------------------------------------
-- 10. CREDIT_TRANSACTIONS TABLE
-- Immutable double-entry financial ledger for skill credit transactions.
-- ----------------------------------------------------------------------------
CREATE TABLE Credit_Transactions (
    transaction_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id       NUMBER NOT NULL CONSTRAINT fk_trans_account REFERENCES Credit_Accounts(account_id) ON DELETE CASCADE,
    session_id       NUMBER CONSTRAINT fk_trans_session REFERENCES Sessions(session_id) ON DELETE SET NULL,
    transaction_type VARCHAR2(20) NOT NULL 
                     CONSTRAINT chk_trans_type CHECK (transaction_type IN ('EARN', 'SPEND', 'REFUND', 'BONUS')),
    amount           NUMBER(10,2) NOT NULL CONSTRAINT chk_trans_amount CHECK (amount > 0),
    transaction_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    description      VARCHAR2(255)
);

-- ----------------------------------------------------------------------------
-- 11. SESSION_ATTENDANCE TABLE
-- Tracks attendance and join/leave times.
-- ----------------------------------------------------------------------------
CREATE TABLE Session_Attendance (
    attendance_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id        NUMBER NOT NULL CONSTRAINT fk_att_session REFERENCES Sessions(session_id) ON DELETE CASCADE,
    user_id           NUMBER NOT NULL CONSTRAINT fk_att_user REFERENCES Users(user_id) ON DELETE CASCADE,
    attendance_status VARCHAR2(20) DEFAULT 'PRESENT' NOT NULL 
                      CONSTRAINT chk_att_status CHECK (attendance_status IN ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED')),
    joined_at         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    left_at           TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 12. RATINGS TABLE (1:1 with completed Session)
-- Feedback and 1-5 star rating provided by learner for the mentor.
-- ----------------------------------------------------------------------------
CREATE TABLE Ratings (
    rating_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      NUMBER NOT NULL CONSTRAINT uk_ratings_session UNIQUE 
                    CONSTRAINT fk_ratings_session REFERENCES Sessions(session_id) ON DELETE CASCADE,
    mentor_id       NUMBER NOT NULL CONSTRAINT fk_ratings_mentor REFERENCES Users(user_id) ON DELETE CASCADE,
    learner_id      NUMBER NOT NULL CONSTRAINT fk_ratings_learner REFERENCES Users(user_id) ON DELETE CASCADE,
    rating          NUMBER(2,1) NOT NULL CONSTRAINT chk_rating_range CHECK (rating BETWEEN 1.0 AND 5.0),
    feedback        VARCHAR2(1000),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_ratings_distinct_users CHECK (mentor_id <> learner_id)
);

-- ----------------------------------------------------------------------------
-- 13. CERTIFICATES TABLE
-- Verifiable completion certificates issued to learners achieving milestones.
-- ----------------------------------------------------------------------------
CREATE TABLE Certificates (
    certificate_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL CONSTRAINT fk_cert_user REFERENCES Users(user_id) ON DELETE CASCADE,
    skill_id         NUMBER NOT NULL CONSTRAINT fk_cert_skill REFERENCES Skills(skill_id) ON DELETE CASCADE,
    certificate_code VARCHAR2(50) NOT NULL CONSTRAINT uk_cert_code UNIQUE,
    issue_date       DATE DEFAULT SYSDATE NOT NULL,
    hours_completed  NUMBER(5,1) DEFAULT 0 NOT NULL CONSTRAINT chk_cert_hours CHECK (hours_completed >= 0),
    status           VARCHAR2(20) DEFAULT 'ISSUED' NOT NULL 
                     CONSTRAINT chk_cert_status CHECK (status IN ('ISSUED', 'REVOKED', 'VERIFIED'))
);

-- ----------------------------------------------------------------------------
-- 14. NOTIFICATIONS TABLE
-- Real-time user notifications.
-- ----------------------------------------------------------------------------
CREATE TABLE Notifications (
    notification_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           NUMBER NOT NULL CONSTRAINT fk_notif_user REFERENCES Users(user_id) ON DELETE CASCADE,
    message           VARCHAR2(500) NOT NULL,
    notification_type VARCHAR2(50) DEFAULT 'GENERAL' NOT NULL 
                      CONSTRAINT chk_notif_type CHECK (notification_type IN (
                          'MATCH_FOUND', 'SESSION_REQUEST', 'SESSION_ACCEPTED', 
                          'SESSION_COMPLETED', 'CREDIT_UPDATE', 'CERTIFICATE_ISSUED', 'GENERAL'
                      )),
    is_read           NUMBER(1) DEFAULT 0 NOT NULL CONSTRAINT chk_notif_read CHECK (is_read IN (0, 1)),
    created_at        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ----------------------------------------------------------------------------
-- 15. REPORTS TABLE
-- Incident reporting and moderation tracking.
-- ----------------------------------------------------------------------------
CREATE TABLE Reports (
    report_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reported_by     NUMBER NOT NULL CONSTRAINT fk_reports_by REFERENCES Users(user_id) ON DELETE CASCADE,
    reported_user   NUMBER NOT NULL CONSTRAINT fk_reports_user REFERENCES Users(user_id) ON DELETE CASCADE,
    session_id      NUMBER CONSTRAINT fk_reports_session REFERENCES Sessions(session_id) ON DELETE SET NULL,
    reason          VARCHAR2(100) NOT NULL,
    description     VARCHAR2(1000) NOT NULL,
    status          VARCHAR2(20) DEFAULT 'OPEN' NOT NULL 
                    CONSTRAINT chk_reports_status CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED', 'DISMISSED')),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    resolved_at     TIMESTAMP
);

-- Useful Performance Indexes
CREATE INDEX idx_userskills_skill ON User_Skills(skill_id);
CREATE INDEX idx_requests_skill ON Skill_Requests(skill_id);
CREATE INDEX idx_sessions_mentor ON Sessions(mentor_id);
CREATE INDEX idx_sessions_learner ON Sessions(learner_id);
CREATE INDEX idx_sessions_status ON Sessions(status);
CREATE INDEX idx_trans_account ON Credit_Transactions(account_id);
CREATE INDEX idx_notif_user_unread ON Notifications(user_id, is_read);

COMMIT;
